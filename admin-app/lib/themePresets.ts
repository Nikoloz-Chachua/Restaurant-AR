export function themePreset(key: unknown) {
  return TEMPLATE_PRESETS.find(preset => preset.key === key) ?? TEMPLATE_PRESETS[0]
}

function hexToRgb(hex: string) {
  const clean = hex.replace('#', '')
  const int = Number.parseInt(clean, 16)
  return `${(int >> 16) & 255},${(int >> 8) & 255},${int & 255}`
}

function isSixDigitHex(value: string) {
  return /^#[0-9a-fA-F]{6}$/.test(value)
}

export function themePresetValuesWithAccents(
  preset: ThemePreset,
  primaryColor?: string,
  secondaryColor?: string,
): ThemeConfig {
  const primary = primaryColor && isSixDigitHex(primaryColor) ? primaryColor : preset.primaryColor
  const secondary = secondaryColor && isSixDigitHex(secondaryColor) ? secondaryColor : preset.secondaryColor
  // Some presets deliberately run a different accent per mode — Floral Rose puts rose
  // on a burgundy night and burgundy on a cream day. Flattening both modes onto one
  // primary would paint its night accent the same colour as its night background, so a
  // preset can opt out for as long as the owner keeps the designed colours. Picking a
  // custom colour still applies to both modes, exactly as every other template does.
  if (preset.preserveModeAccents && primary === preset.primaryColor && secondary === preset.secondaryColor) {
    return { ...preset.values }
  }
  const primaryRgb = hexToRgb(primary)
  const secondaryRgb = hexToRgb(secondary)
  return {
    ...preset.values,
    night_accent: primary,
    day_accent: primary,
    night_accent2: secondary,
    day_accent2: secondary,
    night_border: `rgba(${secondaryRgb},0.22)`,
    day_border: `rgba(${secondaryRgb},0.22)`,
    night_pill_active_bg: `linear-gradient(120deg, ${primary}, ${secondary})`,
    day_pill_active_bg: `linear-gradient(120deg, ${primary}, ${secondary})`,
    night_cta_bg: `linear-gradient(120deg, ${primary}, ${secondary})`,
    day_cta_bg: `linear-gradient(120deg, ${primary}, ${secondary})`,
    night_cta_shadow: `0 7px 20px rgba(${primaryRgb},0.22)`,
    day_cta_shadow: `0 7px 20px rgba(${primaryRgb},0.15)`,
    night_hero_color: primary,
    day_hero_color: primary,
    night_hero_shadow: `0 2px 18px rgba(${primaryRgb},0.22)`,
    day_hero_shadow: `0 2px 14px rgba(${primaryRgb},0.14)`,
    night_divider_bg: `linear-gradient(90deg, transparent, ${secondary}, transparent)`,
    day_divider_bg: `linear-gradient(90deg, transparent, ${secondary}, transparent)`,
    night_accent_edge: `linear-gradient(180deg, ${primary}, ${secondary})`,
    day_accent_edge: `linear-gradient(180deg, ${primary}, ${secondary})`,
  }
}
