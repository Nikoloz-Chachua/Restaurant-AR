import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const fixture = JSON.parse(readFileSync('data/fixtures/baoma-menu.fixture.json', 'utf8'))
const sql = readFileSync('supabase/sql/2026-07-26_baoma_menu_import.sql', 'utf8')
const html = readFileSync('index.html', 'utf8')

assert.equal(fixture.restaurant.id, 53)
assert.equal(fixture.restaurant.slug, 'b-main')
assert.equal(fixture.restaurant.brand_id, 46)
assert.equal(fixture.restaurant.brands.slug, 'b')
assert.equal(fixture.categories.length, 16)
assert.equal(fixture.menu_items.length, fixture.provenance.length)
assert.equal(fixture.menu_items.length, 155, 'BAOMA should include all readable unique rows after serving-size variant consolidation')
assert.ok(fixture.menu_items.every(i => i.restaurant_id === 53), 'all fixture items should be scoped to restaurant 53')
assert.ok(fixture.menu_items.every(i => i.id >= 900000), 'fixture IDs should be synthetic and high')
assert.equal(new Set(fixture.menu_items.map(i => i.id)).size, fixture.menu_items.length, 'fixture item IDs should be unique')
assert.equal(new Set(fixture.menu_items.map(i => i.name_en)).size, fixture.menu_items.length, 'name_en rows must be unique for upsert')
assert.ok(fixture.menu_items.every(i => i.is_3d === false && i.thumb_3d === false && i.model === '' && i.model_usdz === ''), 'BAOMA rows must not be falsely marked 3D/AR')
assert.ok(fixture.menu_items.every(i => i.text_only === !Boolean(i.thumbnail_url)), 'text_only must match thumbnail presence')
assert.ok(fixture.menu_items.filter(i => i.thumbnail_url).every(i => i.thumbnail_url.startsWith('./img/baoma/dishes/')), 'fixture photo URLs should be local')
assert.ok(fixture.provenance.every(p => Array.isArray(p.screenshot_numbers) && p.screenshot_numbers.length), 'each item needs screenshot provenance')
assert.ok(fixture.provenance.some(p => p.conflict_notes), 'conflict notes should be captured internally')
assert.ok(fixture.provenance.some(p => p.translation_status === 'provisional'), 'older-only Georgian translations should be marked provisional')
assert.ok(!fixture.menu_items.some(i => /placeholder|uncertain/i.test(`${i.name_en} ${i.description_en}`)), 'customer-facing copy should not expose uncertainty labels')
assert.ok(!fixture.menu_items.some(i => /coffee-dessert|georgian-beer|chicken-shashlik|alt\.webp/.test(i.thumbnail_url)), 'ambiguous or duplicate crops should not be mapped')
assert.ok(!fixture.menu_items.some(i => /\.00 ₾$/.test(i.price)), 'integer-equivalent prices should not render with .00')
assert.ok(fixture.menu_items.some(i => i.price === '12.90 ₾'), 'explicit decimal source prices should keep two decimals')

const whiteWine = fixture.menu_items.find(i => i.name_en === 'White dry homemade wine')
const redWine = fixture.menu_items.find(i => i.name_en === 'Red dry homemade wine')
const semiSweetWine = fixture.menu_items.find(i => i.name_en === 'Semi-sweet red homemade wine')
const beer = fixture.menu_items.find(i => i.name_en === 'Natakhtari beer')
assert.deepEqual(whiteWine?.variants?.map(v => [v.en, v.price]), [['glass', '8 ₾'], ['0.5 L', '30 ₾'], ['1 L', '45 ₾'], ['1.5 L', '60 ₾']])
assert.deepEqual(redWine?.variants?.map(v => [v.en, v.price]), [['glass', '8 ₾'], ['0.5 L', '30 ₾'], ['1 L', '45 ₾'], ['1.5 L', '60 ₾']])
assert.deepEqual(semiSweetWine?.variants?.map(v => [v.en, v.price]), [['glass', '9 ₾'], ['0.5 L', '35 ₾'], ['1 L', '50 ₾'], ['1.5 L', '70 ₾']])
assert.deepEqual(beer?.variants?.map(v => [v.en, v.price]), [['draft 0.5 L', '8 ₾'], ['bottled 0.5 L', '8 ₾']])
assert.ok(fixture.provenance.filter(p => p.variants?.length).every(p => p.variants.every(v => Array.isArray(v.source) && v.source.length)), 'variant rows should preserve screenshot provenance')
assert.ok(!fixture.menu_items.some(i => /homemade wine —|Natakhtari beer,/.test(i.name_en)), 'serving-size rows should be consolidated into variants')

assert.match(html, /function _baomaFixtureRequested\(\)/)
assert.match(html, /location\.hostname === 'localhost' \|\| location\.hostname === '127\.0\.0\.1'/)
assert.match(html, /_tenantSlugFromHost\(\) === _BAOMA_TENANT_SLUG/)
assert.match(html, /get\('fixture'\) === 'baoma'/)
assert.match(html, /const _previewAccessAllowed = true/)
assert.match(html, /const _analyticsEnabled = !_baomaFixtureRequested\(\)/)
assert.match(html, /if \(!_previewAccessAllowed \|\| !_analyticsEnabled\) return/)

assert.match(sql, /^BEGIN;/m)
assert.match(sql, /ROLLBACK;\s*$/)
assert.ok(!/\nCOMMIT;\s*$/m.test(sql), 'default SQL safety must be rollback')
assert.match(sql, /r\.id = 53/)
assert.match(sql, /r\.slug = 'b-main'/)
assert.match(sql, /r\.brand_id = 46/)
assert.match(sql, /b\.slug = 'b'/)
assert.match(sql, /on conflict \(restaurant_id, name_en\) do update/i)
assert.match(sql, /on conflict \(restaurant_id, key\) do update/i)
assert.match(sql, /where c\.restaurant_id = 53\s+and c\.name_en = src\.category_name_en/i)
assert.match(sql, /addons jsonb,\s+variants jsonb/i)
assert.match(sql, /"variants": \[/)
assert.match(sql, /phone_layout/)
assert.match(sql, /"twin"/)
assert.match(sql, /source menu prices\/translations need client confirmation/i)
assert.match(sql, /photo rights\/quality should be confirmed/i)
assert.ok(!/insert into public\.menu_items\s*\(\s*id\b/i.test(sql), 'production SQL must not insert explicit menu IDs')
assert.ok(!/created_at/i.test(sql), 'production SQL must not set created_at')

console.log(`BAOMA artifact checks passed: ${fixture.menu_items.length} items, ${fixture.categories.length} categories, ${fixture.menu_items.filter(i => i.thumbnail_url).length} photo items`)
