create table if not exists public.brands (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null,
  plan text not null default 'ar_menu',
  logo_url text not null default '',
  primary_color text not null default '',
  secondary_color text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint brands_slug_key unique (slug),
  constraint brands_plan_check check (plan in ('ar_menu', 'full', 'premium')),
  constraint brands_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table if not exists public.restaurants (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references public.brands(id) on delete cascade,
  name text not null,
  slug text not null,
  custom_domain text,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint restaurants_slug_key unique (slug),
  constraint restaurants_custom_domain_key unique (custom_domain),
  constraint restaurants_status_check check (status in ('active', 'inactive')),
  constraint restaurants_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table if not exists public.brand_users (
  brand_id bigint not null references public.brands(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'brand_owner',
  created_at timestamptz not null default now(),
  primary key (brand_id, user_id),
  constraint brand_users_role_check check (role in ('brand_owner'))
);

create table if not exists public.restaurant_users (
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'branch_staff',
  created_at timestamptz not null default now(),
  primary key (restaurant_id, user_id),
  constraint restaurant_users_role_check check (role in ('branch_staff'))
);

