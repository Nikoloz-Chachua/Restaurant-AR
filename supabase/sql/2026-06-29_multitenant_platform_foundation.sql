create or replace function public.fill_event_tenant()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.restaurant_id is null then
    select id into new.restaurant_id
    from public.restaurants
    where slug = 'burger-lions-main'
    limit 1;
  end if;

  if new.brand_id is null and new.restaurant_id is not null then
    select brand_id into new.brand_id
    from public.restaurants
    where id = new.restaurant_id;
  end if;

  return new;
end $$;

