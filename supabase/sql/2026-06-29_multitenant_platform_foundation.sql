create or replace function public.current_app_role()
returns text
language sql
stable
as $$
  select coalesce(
    nullif(auth.jwt() -> 'app_metadata' ->> 'role', ''),
    nullif(auth.jwt() -> 'user_metadata' ->> 'role', '')
  )
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
as $$
  select public.current_app_role() in ('super_admin', 'creator', 'dev')
$$;

create or replace function public.can_access_brand(target_brand_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_super_admin()
    or exists (
      select 1 from public.brand_users bu
      where bu.brand_id = target_brand_id
        and bu.user_id = auth.uid()
    )
    or exists (
      select 1
      from public.restaurant_users ru
      join public.restaurants r on r.id = ru.restaurant_id
      where r.brand_id = target_brand_id
        and ru.user_id = auth.uid()
    )
$$;

